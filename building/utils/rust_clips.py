"""Generate a per-task Rust audio sample file used by the on-device runner.

One clip is enough: the runner just measures timing and per-class scores on a
single sample, so there's no need for labels or multiple test clips.
Written to src/audio_samples/<task>/sample.rs.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import soundfile as sf

from .constants import SAMPLE_RATE, TARGET_AUDIO_LEN
from .paths import REPO_ROOT


def pick_one_clip(task: str, sample_rate: int) -> np.ndarray:
    root = REPO_ROOT / "datasets" / task / "testing"
    if not root.exists():
        raise FileNotFoundError(f"testing dataset not found: {root}")
    for class_dir in sorted(p for p in root.iterdir() if p.is_dir()):
        wavs = sorted(class_dir.glob("*.wav"))
        if not wavs:
            continue
        audio, sr = sf.read(wavs[0], dtype="float32", always_2d=False)
        if sr != sample_rate:
            raise ValueError(f"{wavs[0]} sample rate {sr} != expected {sample_rate}")
        if audio.ndim > 1:
            audio = audio.mean(axis=1)
        return audio.astype(np.float32, copy=False).ravel()
    raise RuntimeError(f"no audio files found under {root}")


def write_audio_sample_rs(
    task: str,
    sample_rate: int = SAMPLE_RATE,
    target_len: int = TARGET_AUDIO_LEN,
    out_root: Path | None = None,
) -> Path:
    audio = pick_one_clip(task, sample_rate)
    if audio.size != target_len:
        raise ValueError(f"expected {target_len} samples, got {audio.size}")

    classes = sorted(
        p.name for p in (REPO_ROOT / "datasets" / task / "training").iterdir()
        if p.is_dir() and p.name != "non_target"
    )
    class_list = ", ".join(f'"{c}"' for c in classes)

    out_dir = (out_root or REPO_ROOT) / "src" / "audio_samples" / task
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "sample.rs"

    values = ", ".join(f"{v:.8f}" for v in audio)
    out_path.write_text(
        f"// Generated by building/utils/rust_clips.py for task={task}\n"
        f"pub const SAMPLE_RATE: usize = {sample_rate};\n"
        f"pub const NUM_CLASSES: usize = {len(classes)};\n"
        f"pub const CLASS_NAMES: [&str; NUM_CLASSES] = [{class_list}];\n"
        f"pub const AUDIO: &[f32] = &[{values}];\n",
        encoding="utf-8",
    )
    return out_path
